#!/usr/bin/env python3
"""syntheprise_sync.py — generate runnable, per-tool slash-commands and skills from the
single canonical source in `.agents/`.

Problem this solves (v5.2 gap G2): workflows/skills lived only as documentation
in `.agents/`, so Claude Code / Codex users had no real `/plan`, `/review`, `/adr`
commands, and the few mirrored skills drifted out of sync.

Canonical source of truth:
  .agents/workflows/<name>.md              (front matter: description) — the single
                                           source for a command's steps.
  .agents/skills/<name>/SKILL.md           hand-authored skill (front matter: name,
                                           description) — canonical source.

Generated (DO NOT EDIT — regenerate with `syntheprise sync`):
  .agents/skills/source-command-<name>/SKILL.md
                                           GENERATED from .agents/workflows/<name>.md —
                                           its "Command Template" is the workflow body;
                                           do not hand-edit.
  .claude/commands/<name>.md               Claude Code slash commands (from workflow)
  .claude/skills/<name>/SKILL.md           Claude Code skills (mirror of the .agents skill)
  .codex/prompts/<name>.md                 Codex slash prompts (from workflow)
  CLAUDE.md                                Claude Code constitution (mirror of AGENTS.md)
Antigravity reads `.agents/` natively, so no adapter generation is required for it.

Modes:
  syntheprise_sync.py            regenerate all adapter files
  syntheprise_sync.py --check    verify parity only (CI); non-zero exit if drift/missing
"""
from __future__ import annotations
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WORKFLOWS = REPO / ".agents" / "workflows"
SKILLS = REPO / ".agents" / "skills"
GEN_MARK = "syntheprise sync"


def _split_frontmatter(text: str):
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            head = text[3:end].strip("\n")
            body = text[end + 4:].lstrip("\n")
            return head, body
    return "", text


def _fm_value(head: str, key: str) -> str:
    for line in head.splitlines():
        s = line.strip()
        if s.startswith(key + ":"):
            return s[len(key) + 1:].strip()
    return ""


def _expected_claude_command(name: str, src: Path) -> str:
    head, body = _split_frontmatter(src.read_text(encoding="utf-8"))
    desc = _fm_value(head, "description") or f"Syntheprise Framework workflow: {name}"
    return (
        f"---\ndescription: {desc}\n---\n"
        f"<!-- GENERATED BY `{GEN_MARK}` from .agents/workflows/{name}.md — DO NOT EDIT. -->\n\n"
        f"{body.rstrip()}\n"
    )


def _expected_codex_prompt(name: str, src: Path) -> str:
    head, body = _split_frontmatter(src.read_text(encoding="utf-8"))
    desc = _fm_value(head, "description") or f"Syntheprise Framework workflow: {name}"
    return (
        f"# /{name}\n"
        f"<!-- GENERATED BY `{GEN_MARK}` from .agents/workflows/{name}.md — DO NOT EDIT. -->\n"
        f"> {desc}\n\n"
        f"{body.rstrip()}\n"
    )


def _mirror_text(text: str, src_rel: str) -> str:
    # Keep front matter first so doctor.py still sees name/description, then the marker.
    head, body = _split_frontmatter(text)
    marker = f"<!-- GENERATED BY `{GEN_MARK}` from {src_rel} — DO NOT EDIT. -->"
    if head:
        return f"---\n{head}\n---\n{marker}\n\n{body.rstrip()}\n"
    return f"{marker}\n{body.rstrip()}\n"


def _expected_skill_mirror(src: Path) -> str:
    return _mirror_text(src.read_text(encoding="utf-8"), str(src.relative_to(REPO)))


def _expected_source_command_skill(name: str, wf: Path) -> str:
    # The `source-command-<name>` skill's "Command Template" is REGENERATED from
    # the workflow (honoring its own DO-NOT-EDIT banner), so it can no longer
    # drift from `.agents/workflows/<name>.md`.
    head, body = _split_frontmatter(wf.read_text(encoding="utf-8"))
    desc = _fm_value(head, "description") or f"Syntheprise Framework workflow: {name}"
    marker = f"<!-- GENERATED BY `{GEN_MARK}` from .agents/workflows/{name}.md — DO NOT EDIT. -->"
    return (
        f'---\nname: "source-command-{name}"\ndescription: "{desc}"\n---\n'
        f"# source-command-{name}\n\n"
        f"Use this skill when the user asks to run the migrated source command `{name}`.\n\n"
        f"## Command Template\n\n"
        f"{marker}\n\n"
        f"{body.rstrip()}\n"
    )


def _expected_claude_md() -> str:
    # CLAUDE.md drifted when maintained by hand (missed AGENTS.md rule additions),
    # so it is generated like every other adapter file.
    src = REPO / "AGENTS.md"
    marker = (
        f"<!-- GENERATED BY `{GEN_MARK}` from AGENTS.md — DO NOT EDIT. "
        f"Edit AGENTS.md and run `./syntheprise sync`. -->"
    )
    return f"{marker}\n\n{src.read_text(encoding='utf-8').rstrip()}\n"


def _plan():
    """Return list of (dest_path, expected_content).

    Only generate for tools whose adapter directory is present, so an
    adapter-pruned project (e.g. `syntheprise init --adapter claude`) does not get
    foreign-tool files regenerated.
    """
    has_claude = (REPO / ".claude").exists()
    has_codex = (REPO / ".codex").exists()
    plan = []
    # `source-command-<name>` skills are regenerated from their workflow; cache the
    # expected content so the `.claude/skills` mirror below reflects the REGENERATED
    # source (not the pre-sync on-disk copy) within a single run — else the mirror
    # would need a second `syntheprise sync` to converge.
    sc_expected: dict[str, str] = {}
    for wf in sorted(WORKFLOWS.glob("*.md")):
        name = wf.stem
        sc_skill = SKILLS / f"source-command-{name}" / "SKILL.md"
        # A `source-command-<name>` skill is generated for EVERY workflow (not
        # only ones that already exist on disk), so a fresh kit bootstraps the
        # full set and each command is discoverable as a skill without drift.
        content = _expected_source_command_skill(name, wf)
        sc_expected[f"source-command-{name}"] = content
        plan.append((sc_skill, content))  # canonical .agents source (Antigravity reads natively)
        if has_claude:
            plan.append((REPO / ".claude" / "commands" / f"{name}.md", _expected_claude_command(name, wf)))
        if has_codex:
            plan.append((REPO / ".codex" / "prompts" / f"{name}.md", _expected_codex_prompt(name, wf)))
    if has_claude:
        # Mirror every skill into .claude/skills: hand-authored skill dirs found
        # on disk, plus the generated source-command skills (which may not exist
        # on disk yet on a first run — using the cached regenerated content keeps
        # the mirror converging in a single pass).
        mirrors: dict[str, str] = {}
        for sk in sorted(SKILLS.glob("*/SKILL.md")):
            folder = sk.parent.name
            src_rel = str(sk.relative_to(REPO))
            if folder in sc_expected:
                mirrors[folder] = _mirror_text(sc_expected[folder], src_rel)
            else:
                mirrors[folder] = _expected_skill_mirror(sk)
        for folder, content in sc_expected.items():
            if folder not in mirrors:
                mirrors[folder] = _mirror_text(content, f".agents/skills/{folder}/SKILL.md")
        for folder in sorted(mirrors):
            plan.append((REPO / ".claude" / "skills" / folder / "SKILL.md", mirrors[folder]))
        if (REPO / "AGENTS.md").exists():
            plan.append((REPO / "CLAUDE.md", _expected_claude_md()))
    return plan


def sync(check: bool) -> int:
    plan = _plan()
    drift, written = [], 0
    for dest, expected in plan:
        current = dest.read_text(encoding="utf-8") if dest.exists() else None
        if check:
            if current != expected:
                drift.append(dest.relative_to(REPO))
        else:
            if current != expected:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(expected, encoding="utf-8")
                written += 1
    if check:
        if drift:
            print("syntheprise sync --check: ADAPTERS OUT OF SYNC. Run `syntheprise sync`. Drifted:")
            for d in drift:
                print(f"  - {d}")
            return 1
        print(f"syntheprise sync --check: OK — {len(plan)} adapter files in sync.")
        return 0
    print(f"syntheprise sync: {written} file(s) updated, {len(plan)} total in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(sync("--check" in sys.argv[1:]))
