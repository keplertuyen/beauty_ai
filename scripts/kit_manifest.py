#!/usr/bin/env python3
"""kit_manifest.py — the single, explicit policy for what the Syntheprise Framework kit distributes
into a scaffolded project (v5.7.4 project/framework boundary).

The framework repo is NOT a project template by "copy every tracked file minus a
short denylist" — that leaks the kit's own change history, state snapshots,
dashboard, roadmap, research and operating mode into every generated project.

`is_distributable(rel)` answers: does this repo-relative path belong in a fresh
project? Only templates and canonical/reusable content do. Framework-instance
state is framework-only and is regenerated clean by the initializer.
"""
import re

# Framework-only PREFIXES — never copied into a project.
FRAMEWORK_ONLY_PREFIXES = (
    ".syntheprise-kit",
    ".syntheprise/",                      # machine-readable descriptor — regenerated per project
    ".syntheprise-quality.yml",          # regenerated per project (with its own mode)
    "presets/",                    # the kit's stack/preset registry
    "docs/company-rollout/",       # Syntheprise adoption program assets
    "docs/_dashboard/",            # regenerated clean (0 active / 0 archived)
    "docs/_guides/04-v5-core-build-guide",
)


def _is_template_name(name: str) -> bool:
    return name.endswith("-template.md") or name.endswith("-template") or "-template/" in name


def is_distributable(rel: str) -> bool:
    rel = rel.replace("\\", "/")

    if rel.startswith(FRAMEWORK_ONLY_PREFIXES):
        return False

    # Change lifecycle: only the *-template scaffolds travel; instances/archive stay.
    if rel.startswith("docs/_changes/"):
        return "-template/" in rel or rel.rstrip("/").endswith("-template")

    # State snapshots: only the template; real snapshots and archive stay.
    if rel.startswith("docs/_states/"):
        return rel == "docs/_states/STATE-template.md"

    # Plans: only the *-template files; MASTER/PHASE/WG instances stay (a fresh
    # MASTER-PLAN.md is generated by the initializer).
    if rel.startswith("docs/_plans/"):
        return _is_template_name(rel.split("/")[-1])

    # Research: keep the governance README; drop the kit's own research notes.
    if rel.startswith("docs/_research/"):
        return rel == "docs/_research/README.md"

    # Review records: keep a README if present; drop real review records.
    if rel.startswith("docs/_review/"):
        return rel.endswith("/README.md")

    # ADRs: keep the template and the 0001 baseline example; drop the kit's own
    # framework decisions (0002+).
    if rel.startswith("docs/adr/"):
        base = rel.split("/")[-1]
        if base == "ADR-template.md" or base.startswith("0001-"):
            return True
        if re.match(r"\d{4}-", base):
            return False
        return True

    return True
