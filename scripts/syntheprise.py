def _included(rel: str, tier: int, adapter: str) -> bool:
    if any(part in JUNK for part in rel.split("/")):
        return False
    if rel == ".git" or rel.startswith(".git/"):
        return False
    if rel == ".syntheprise-kit":  # framework-repo marker; generated projects get .syntheprise-project
        return False
    if rel.startswith(ALWAYS_DROP_PREFIXES):
        return False
    for d in ADAPTER_DROP[adapter]:
        if rel == d or rel.startswith(d + "/"):
            return False
    if tier < 2 and (rel in TIER2_ONLY or any(rel.startswith(p + "/") or rel == p for p in TIER2_ONLY)):
        return False
    if tier < 1 and rel.startswith(TIER1_PLUS_PREFIXES):
        return False
    return True




