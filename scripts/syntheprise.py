def _scan_codebase(max_files: int = 3000) -> dict[str, list[tuple[str, str, str]]]:
    """Return evidence-backed inventory buckets for a brownfield repo."""
    exclude = {'.git', '.agents', '.claude', '.codex', '.adapters', 'docs', 'scripts', 'node_modules', '.venv', 'venv', 'dist', 'build', 'coverage', '__pycache__'}
    buckets: dict[str, list[tuple[str, str, str]]] = {
        'Languages / stack': [], 'Entrypoints / services': [], 'Data stores / migrations': [],
        'External integrations': [], 'Build / CI / deploy': [], 'Existing tests': [],
        'Dependencies': [], 'High-risk / unknowns': []
    }
    ext_lang = {
        '.cs': 'C#/.NET', '.fs': 'F#/.NET', '.js': 'JavaScript', '.jsx': 'React/JSX', '.ts': 'TypeScript', '.tsx': 'React/TSX',
        '.py': 'Python', '.java': 'Java', '.go': 'Go', '.php': 'PHP', '.rb': 'Ruby', '.sql': 'SQL', '.vue': 'Vue', '.cshtml': 'Razor'
    }
    counts: dict[str, int] = {}
    seen = 0
    for p in sorted(REPO.rglob('*')):
        if not p.is_file():
            continue
        rel = p.relative_to(REPO)
        if any(part in exclude for part in rel.parts):
            continue
        if p.name.startswith('.') and p.name not in {'.env.example'}:
            continue
        seen += 1
        if seen > max_files:
            buckets['High-risk / unknowns'].append(('scan-limit', f'scan stopped after {max_files} files', 'medium'))
            break
        ext = p.suffix.lower()
        if ext in ext_lang:
            counts[ext_lang[ext]] = counts.get(ext_lang[ext], 0) + 1
        lname = p.name.lower()
        srel = str(rel).replace(os.sep, '/')
        if lname in {'package.json', 'pyproject.toml', 'requirements.txt', 'pom.xml', 'build.gradle', 'go.mod'} or ext == '.csproj':
            buckets['Dependencies'].append((srel, 'dependency manifest', 'high'))
        if lname in {'dockerfile', 'docker-compose.yml', 'compose.yml', 'azure-pipelines.yml'} or srel.startswith('.github/workflows/'):
            buckets['Build / CI / deploy'].append((srel, 'build/deploy/CI evidence', 'high'))
        if re.search(r'(^|/)(test|tests|spec|__tests__)(/|$)', srel, re.I) or re.search(r'(test|spec)\.(cs|js|jsx|ts|tsx|py)$', lname):
            buckets['Existing tests'].append((srel, 'test evidence', 'medium'))
        if lname in {'program.cs', 'startup.cs', 'main.py', 'app.py', 'manage.py', 'server.js', 'server.ts', 'index.js', 'index.ts', 'vite.config.ts', 'next.config.js'}:
            buckets['Entrypoints / services'].append((srel, 'probable application entrypoint/config', 'medium'))
        if 'migration' in srel.lower() or lname in {'schema.prisma', 'dbcontext.cs'} or ext == '.sql':
            buckets['Data stores / migrations'].append((srel, 'data/schema/migration evidence', 'medium'))
        if lname.endswith(('.json', '.yml', '.yaml', '.config', '.xml')):
            try:
                txt = p.read_text(encoding='utf-8', errors='ignore')[:20000]
                if re.search(r'(?i)(api[_-]?url|base[_-]?url|connectionstring|endpoint|webhook|oauth|saml|smtp|redis|kafka|rabbit|s3|blob)', txt):
                    buckets['External integrations'].append((srel, 'configuration suggests external integration', 'low'))
            except Exception:
                pass
    for lang, count in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        buckets['Languages / stack'].append((lang, f'{count} source file(s)', 'medium'))
    for key in buckets:
        if not buckets[key]:
            buckets[key].append(('not detected', 'requires human confirmation', 'low'))
    return buckets


