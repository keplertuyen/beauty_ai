def cmd_gate(args) -> int:
    """Quality gate, auto-detecting repository type so it is reproducibly green
    in the right environment:

      .syntheprise-project present  -> strict project gate (doctor --quality-gate)
      .syntheprise-kit present       -> framework/template gate (doctor --template +
                                 version-consistency + change-completeness)
      neither                 -> strict (safe default)

    Override with `--framework` / `--project`.
    """
    is_project = (REPO / ".syntheprise-project").exists()
    is_kit = (REPO / ".syntheprise-kit").exists()
    mode = "project"
    if getattr(args, "framework", False):
        mode = "framework"
    elif getattr(args, "project", False):
        mode = "project"
    elif is_kit and not is_project:
        mode = "framework"
    if mode == "framework":
        rc = _run([PY, str(SCRIPTS / "doctor.py"), "--template"])
        rc |= _run([PY, str(SCRIPTS / "check-version-consistency.py")])
        rc |= _run([PY, str(SCRIPTS / "check-change-completeness.py")])
        rc |= _run([PY, str(SCRIPTS / "check-lifecycle-consistency.py")])
        rc |= _run([PY, str(SCRIPTS / "check-component-lifecycle.py")])
        rc |= _run([PY, str(SCRIPTS / "check-workflow-security.py")])
        rc |= _run([PY, str(SCRIPTS / "check-dependencies.py"), "--strict"])
        rc |= _run([PY, str(SCRIPTS / "check-secrets.py")])
        rc |= _run([PY, str(SCRIPTS / "check-traceability.py")])
        rc |= _run([PY, str(SCRIPTS / "check-doc-drift.py"), "--strict"])
    else:
        rc = _run([PY, str(SCRIPTS / "doctor.py"), "--quality-gate"])
        rc |= _run([PY, str(SCRIPTS / "check-lifecycle-consistency.py")])
        rc |= _run([PY, str(SCRIPTS / "check-doc-drift.py"), "--strict"])
        if _integrations_enforced():
            rc |= _run([PY, str(SCRIPTS / "syntheprise.py"), "integrations", "--strict"])
    rc |= _run([PY, str(SCRIPTS / "syntheprise_sync.py"), "--check"])
    return rc


def _integrations_enforced() -> bool:
    """Opt-in: a project fails the gate on integration drift only when its
    `.syntheprise-quality.yml` declares `integrations: strict` (under a `gate:` block or at
    top level). Default off, so scaffolds that have not filled the Integrations table
    are never failed; `syntheprise integrations` stays advisory until a team opts in."""
    txt = (REPO / ".syntheprise-quality.yml").read_text(encoding="utf-8") if (REPO / ".syntheprise-quality.yml").exists() else ""
    return re.search(r"(?m)^\s*integrations:\s*strict\b", txt) is not None


