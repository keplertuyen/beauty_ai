# Path segments never copied by the rglob fallback (git ls-files already
# excludes these because they are ignored/untracked; this is defense-in-depth).
_HARDENED_EXCLUDE_PARTS = {
    ".git", ".venv", "venv", "node_modules", "__pycache__", "dist", "build",
    ".pytest_cache", ".ruff_cache", "secrets", "worktrees",
}


# Environment-file policy in ONE place (used by the initializer; the secret
# scanner keeps its own allowlist but agrees on these safe templates). Real
# secret env files are excluded; intentional templates are kept.
_ENV_TEMPLATE_ALLOW = {".env.example", ".env.template", ".env.sample"}


def _is_secret_env(rel: str) -> bool:
    base = rel.rsplit("/", 1)[-1]
    if base in _ENV_TEMPLATE_ALLOW:
        return False
    return base == ".env" or base.startswith(".env.")


def _base_kit_files(tier: int, adapter: str, root: Path = REPO) -> list[str]:
    """Relative paths of base-kit files to copy.

    Source of truth is `git ls-files` (tracked files only) so ignored/untracked
    paths — real `.env`, nested `.claude/worktrees/`, local artifacts — are never
    copied into a new project (a secrets-leak and bloat vector). Falls back to a
    hardened `rglob` when the kit is not a git work tree (e.g. downloaded ZIP).
    Intentional templates (`.env.example`) ARE kept. `root` is overridable for tests.
    """
    tracked: list[str] | None = None
    try:
        res = subprocess.run(["git", "ls-files", "-z"], cwd=root,
                             capture_output=True, text=True, timeout=60)
        if res.returncode == 0:
            tracked = [x for x in res.stdout.split("\0") if x]
    except Exception:
        tracked = None

    if tracked is not None:
        candidates = tracked
    else:
        candidates = []
        for p in root.rglob("*"):
            if not p.is_file():
                continue
            rel = str(p.relative_to(root)).replace(os.sep, "/")
            if any(seg in _HARDENED_EXCLUDE_PARTS for seg in rel.split("/")):
                continue
            candidates.append(rel)

    sys.path.insert(0, str(SCRIPTS))
    import kit_manifest
    out = []
    for rel in candidates:
        if _is_secret_env(rel):
            continue
        if not kit_manifest.is_distributable(rel):
            continue  # framework-only instance state — never leaks into a project
        if not _included(rel, tier, adapter):
            continue
        out.append(rel)
    return sorted(set(out))


def _copy_base_kit(target: Path, tier: int, adapter: str, root: Path = REPO) -> int:
    """Copy the tier/adapter-filtered, Git-tracked base kit from root into target."""
    target.mkdir(parents=True, exist_ok=True)
    copied = 0
    for rel in _base_kit_files(tier, adapter, root):
        src = root / rel
        if not src.is_file():
            continue
        dest = target / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
        copied += 1
    return copied


def _dir_nonempty(target: Path) -> bool:
    return target.exists() and target.is_dir() and any(target.iterdir())


def _deploy_from_staging(staging: Path, target: Path, force: bool = False) -> None:
    """Move a fully-built staging tree into target.

    New/empty target: a single atomic `os.replace` (rename) — a failure leaves
    NO partial target. `--force` into an existing target: transactional overlay —
    back up each file before overwriting, then on any error restore the backup
    and remove created files, so a failed deploy never half-modifies the target.
    Staging must sit on the same filesystem as target (callers create it under
    target.parent) so the rename is atomic.
    """
    if target.is_symlink():
        raise OSError(f"refusing to deploy onto a symlinked target: {target}")
    if not _dir_nonempty(target):
        if target.exists():
            target.rmdir()  # empty dir — replace atomically
        target.parent.mkdir(parents=True, exist_ok=True)
        os.replace(staging, target)
        return
    # force overlay onto a non-empty target, with full rollback (files AND the
    # directories we create) so a failed deploy leaves the target unchanged.
    root = target.resolve()
    files = [p for p in sorted(staging.rglob("*")) if p.is_file()]
    backup = Path(tempfile.mkdtemp(prefix=".syntheprise-bak-", dir=str(target.parent)))
    created: list[Path] = []
    overwritten: list[Path] = []
    created_dirs: list[Path] = []

    def _reject_symlink_escape(dst: Path):
        # F1: never write through a symlinked path component — that could place
        # files OUTSIDE the target. --force means overwrite INSIDE target, not
        # follow-symlink-out.
        cur = target
        for part in dst.relative_to(target).parts:
            cur = cur / part
            if cur.is_symlink():
                raise OSError(f"refusing to write through symlink: {cur}")

    def _mkparents(path: Path):
        missing = []
        cur = path.parent
        while not cur.exists():
            missing.append(cur)
            cur = cur.parent
        for dd in reversed(missing):
            dd.mkdir()
            created_dirs.append(dd)

    try:
        for p in files:
            rel = p.relative_to(staging)
            dst = target / rel
            _reject_symlink_escape(dst)
            if dst.exists():
                b = backup / rel
                b.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(dst, b)
                overwritten.append(rel)
            else:
                created.append(rel)
            _mkparents(dst)
            shutil.copy2(p, dst)
    except Exception as orig:
        # F8: best-effort rollback that does not abort on the first error, and
        # keeps the recovery backup if rollback could not fully complete.
        rb_errors = []
        for rel in created:
            try:
                (target / rel).unlink(missing_ok=True)
            except Exception as e:
                rb_errors.append(f"unlink {rel}: {e}")
        for rel in overwritten:
            try:
                (target / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(backup / rel, target / rel)
            except Exception as e:
                rb_errors.append(f"restore {rel}: {e}")
        for dd in sorted(created_dirs, key=lambda x: len(x.parts), reverse=True):
            try:
                dd.rmdir()
            except OSError:
                pass
        if rb_errors:
            raise OSError(
                f"deploy failed ({orig}); rollback INCOMPLETE — recovery backup kept at {backup}. "
                f"Errors: {'; '.join(rb_errors)}"
            ) from orig
        shutil.rmtree(backup, ignore_errors=True)
        raise
    else:
        shutil.rmtree(backup, ignore_errors=True)


