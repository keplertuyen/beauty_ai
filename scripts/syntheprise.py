# ---------------------------------------------------------------------------
# Git hook bootstrap — guarantee the worktree-isolation guard runs on EVERY
# local commit. The guard skips in CI by design (a local working-state check),
# so it cannot be enforced by a CI job — the only reliable enforcement is a
# locally-installed pre-commit hook. The mandated `./syntheprise worktree` /
# `./syntheprise close-out` / `./syntheprise setup-hooks` entry points self-install it.
# ---------------------------------------------------------------------------
_NATIVE_PRECOMMIT_HOOK = """#!/usr/bin/env bash
# Syntheprise Framework native pre-commit fallback. Guarantees the worktree-isolation guard runs
# locally even without the pre-commit framework. Install the full hook suite
# anytime with:
#   pipx install pre-commit && pre-commit install
set -euo pipefail
root="$(git rev-parse --show-toplevel)"
exec python3 "$root/scripts/check-worktree-isolation.py"
"""


def _git_hooks_dir() -> Path | None:
    """Common hooks dir (shared across all linked worktrees)."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--git-common-dir"],
            cwd=REPO, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:
        return None
    common = Path(out)
    if not common.is_absolute():
        common = (REPO / common).resolve()
    return common / "hooks"


def _ensure_git_hooks() -> None:
    """Best-effort: guarantee the worktree-isolation guard runs on every commit.

    Prefers the pre-commit framework (full hook suite) when the `pre-commit` CLI
    is available; otherwise installs a dependency-free native hook that runs the
    worktree-isolation guard. Never raises — must not block the mandated workflow.
    """
    try:
        if shutil.which("pre-commit"):
            _run(["pre-commit", "install"])
            return
        hooks = _git_hooks_dir()
        if hooks is None:
            return
        hook = hooks / "pre-commit"
        if hook.exists():
            txt = hook.read_text(encoding="utf-8", errors="ignore")
            if "pre-commit.com" in txt or "File generated by pre-commit" in txt:
                return  # framework-managed hook already present — leave it
            if "Syntheprise Framework native pre-commit fallback" in txt:
                return  # our native hook already installed
        hooks.mkdir(parents=True, exist_ok=True)
        hook.write_text(_NATIVE_PRECOMMIT_HOOK, encoding="utf-8")
        hook.chmod(0o755)
        print(
            "Installed native pre-commit worktree-isolation guard (pre-commit "
            "framework not found). Full suite: pipx install pre-commit && pre-commit install"
        )
    except Exception as e:  # best-effort — never block the mandated workflow
        print(f"Warning: could not install git hook (skipping, not blocking): {e}")


