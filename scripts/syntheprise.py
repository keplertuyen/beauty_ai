def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.strip().lower()).strip("-")


def cmd_worktree(args) -> int:
    """Create an isolated git worktree for a change/task (worktree isolation)."""
    slug = _slug(args.change_id)
    if not slug:
        print("A <change-id> is required, e.g.: ./syntheprise worktree gov-2026-004-worktree-isolation")
        return 1
    path = REPO.parent / f"{REPO.name}-{slug}"
    branch = args.branch or f"change/{slug}"
    base = args.base or "origin/main"
    if path.exists():
        print(f"Already exists: {path} (reuse it or pick another name).")
        return 1
    _run(["git", "fetch", "origin", "--prune"])
    rc = _run(["git", "worktree", "add", "-b", branch, str(path), base])
    if rc == 0:
        _ensure_git_hooks()  # shared hooks dir -> guard active in the new worktree too
        print(f"\nWorktree: {path}\n   Branch: {branch} (off {base})")
        print("   Do ALL git-write work (branch/commit/close-out) in this worktree.")
        print(f"   When done: git worktree remove {path}")
    return rc


def cmd_update_branch(args) -> int:
    """Keep the current work branch current with origin/<base> before PR/merge.

    Branch protection on `main` is typically strict (require up-to-date), so an
    out-of-date branch cannot be merged. Run this before `gh pr create` and
    again right before merging if `main` has advanced. Merges origin/<base> in
    (no force-push needed); stops on conflict for manual resolution.
    """
    base = args.base or "main"
    if _run(["git", "fetch", "origin", "--prune"]) != 0:
        return 1
    try:
        behind = subprocess.run(
            ["git", "rev-list", "--count", f"HEAD..origin/{base}"],
            cwd=REPO, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:
        behind = "?"
    if behind == "0":
        print(f"Branch is up-to-date with origin/{base} — ready for PR/merge.")
        return 0
    print(f"Branch is {behind} commit(s) behind origin/{base} — merging in to avoid 'out-of-date'...")
    rc = _run(["git", "merge", "--no-edit", f"origin/{base}"])
    if rc != 0:
        print("Merge conflict — resolve manually + commit, then `git push`.")
        return rc
    print("Updated. Next: `git push` -> wait for green CI -> merge (while the branch is still up-to-date).")
    return 0


def cmd_setup_hooks(args) -> int:
    """Install the git pre-commit guard hook (worktree isolation). Idempotent."""
    _ensure_git_hooks()
    return 0


def cmd_closeout(args) -> int:
    """Serialize close-out via session-lock + enforce worktree isolation."""
    import session_lock as sl

    _ensure_git_hooks()  # make sure the local guard is active before any git-write sequence
    if args.release:
        sl.release()
        print("Released the close-out session-lock.")
        return 0
    if args.status:
        info = sl.read()
        print(json.dumps(info, indent=2, ensure_ascii=False) if info else "No close-out lock held.")
        return 0
    if sl.is_main_worktree():
        print("close-out MUST run inside a dedicated worktree, not the primary checkout.")
        print("   Create one: ./syntheprise worktree <change-id>")
        return 1
    if not sl.acquire("close-out"):
        info = sl.read() or {}
        print(f"Another session holds the close-out lock: worktree={info.get('worktree')} "
              f"branch={info.get('branch')}. Wait or coordinate.")
        return 1
    print("Acquired session-lock. Proceed with close-out per the Definition of Done.")
    print("   When done: ./syntheprise close-out --release")
    return 0


