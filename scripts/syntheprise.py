def _detected_kit_version(project: Path) -> str | None:
    managed = project / ".syntheprise" / "managed-files.json"
    if managed.is_file():
        try:
            value = json.loads(managed.read_text(encoding="utf-8"))
            version = value.get("kit_version")
            if isinstance(version, str) and version.strip():
                return version.strip()
        except (OSError, json.JSONDecodeError):
            pass
    version_file = project / "VERSION"
    if version_file.is_file():
        value = version_file.read_text(encoding="utf-8", errors="ignore").strip()
