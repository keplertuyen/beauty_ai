def _available_stacks() -> list[str]:
    if not STACKS_DIR.exists():
        return []
    return sorted(p.name for p in STACKS_DIR.iterdir()
                  if p.is_dir() and (p / "manifest.yaml").exists())


def _stack_field(name: str, field: str, default: str = "") -> str:
    manifest = STACKS_DIR / name / "manifest.yaml"
    if not manifest.exists():
        return default
    m = re.search(rf"(?m)^{re.escape(field)}:\s*(.+?)\s*$",
                  manifest.read_text(encoding="utf-8", errors="ignore"))
    return m.group(1).strip().strip('"').strip("'") if m else default


def _stack_default_tier(name: str) -> int:
    v = _stack_field(name, "default_tier", "1")
    return int(v) if v in ("0", "1", "2") else 1


def _stack_required_tools(name: str) -> list[str]:
    """Parse the legacy scalar without introducing a YAML dependency."""
    raw = _stack_field(name, "required_tools")
    return sorted({item.strip() for item in raw.split(",") if item.strip()})


def _missing_required_tools(required_tools, *, which=shutil.which) -> list[str]:
    """Return a deterministic list of executable names absent from PATH."""
    return sorted({
        tool for tool in required_tools
        if tool and which(tool) is None
    })


def _warn_missing_required_tools(required_tools) -> None:
    missing = _missing_required_tools(required_tools, which=shutil.which)
    if not missing:
        return
    print(
        "\nWARNING: scaffold created successfully, but required tool(s) are "
        "not available on PATH: " + ", ".join(missing),
        file=sys.stderr,
    )
    print(
        "Install the missing toolchain before running the generated dev/build/"
        "test commands. No setup command was executed.",
        file=sys.stderr,
    )


def _composition_registries():
    """Load v2 component/blueprint registries lazily.

    Lazy import keeps legacy `init` / `new --stack` behavior isolated from the
    v2 engine and avoids import work for commands that do not use stack packs.
    """
    import stack_composition
    return (
        stack_composition,
        stack_composition.discover_components(COMPONENTS_DIR),
        stack_composition.discover_blueprints(BLUEPRINTS_DIR),
    )


def _resolve_composition_args(args):
    stack_composition, components, blueprints = _composition_registries()
    blueprint = getattr(args, "blueprint", None)
    selectors = {
        "backend": getattr(args, "backend", None),
        "web": getattr(args, "web", None),
        "mobile": getattr(args, "mobile", None),
    }
    if blueprint:
        if any(selectors.values()):
            raise stack_composition.StackResolutionError(
                "conflicting-selection",
                "--blueprint cannot be combined with --backend/--web/--mobile",
            )
        return stack_composition, stack_composition.resolve_blueprint(
            components, blueprints, blueprint
        )
    if not selectors["backend"]:
        raise stack_composition.StackResolutionError(
            "missing-backend",
            "composition requires --backend or --blueprint",
        )
    selected = [
        stack_composition.select_component(components, role, value)
        for role, value in selectors.items() if value
    ]
    return stack_composition, stack_composition.resolve_plan(components, selected)


def _print_composition_plan(plan) -> None:
    print("Resolved Syntheprise Framework composition:")
    if plan.get("blueprint"):
        print(f"  blueprint: {plan['blueprint']} ({plan['certification']})")
    for component in plan["components"]:
        print(f"  - {component['role']}: {component['id']} -> {component['output']}")
    print("  ports: " + (", ".join(str(p) for p in plan["ports"]) or "(none)"))
    print(
        "  required tools: "
        + (", ".join(plan["required_tools"]) or "(none)")
    )
    provides = plan["contracts"]["provides"]
    print("  contracts: " + (", ".join(provides) or "(none)"))


def _apply_stack_pack(target: Path, name: str) -> int:
    """Copy a stack pack's runnable skeleton + doc overrides into target.

    skeleton/ -> target/ (verbatim); docs/ -> target/docs/ (overwrite the
    placeholder base docs, e.g. tech-stack.md / architecture.md for the stack).
    """
    pack = STACKS_DIR / name
    if not pack.exists():
        print(f"unknown stack: {name}", file=sys.stderr)
        print("available stacks: " + (", ".join(_available_stacks()) or "(none)"), file=sys.stderr)
        return -1
    copied = 0
    for sub in ("skeleton", "docs"):
        root = pack / sub
        if not root.exists():
            continue
        base = target if sub == "skeleton" else target / "docs"
        for p in sorted(root.rglob("*")):
            if not p.is_file():
                continue
            dest = base / p.relative_to(root)
            dest.parent.mkdir(parents=True, exist_ok=True)
            # Merge .gitignore rather than overwrite, so the base kit's required
            # ignores (e.g. __MACOSX, ._*) survive alongside stack-specific rules.
            if dest.name == ".gitignore" and dest.exists():
                have = dest.read_text(encoding="utf-8")
                have_lines = set(have.splitlines())
                extra = [ln for ln in p.read_text(encoding="utf-8").splitlines()
                         if ln.strip() and ln not in have_lines]
                if extra:
                    sep = "" if have.endswith("\n") else "\n"
                    dest.write_text(have + sep + f"\n# --- {name} stack ---\n"
                                    + "\n".join(extra) + "\n", encoding="utf-8")
            else:
                shutil.copy2(p, dest)
            copied += 1
    (target / ".syntheprise-stack").write_text(f"{name}\n", encoding="utf-8")
    return copied


def _generate_project_state(staging: Path, mode: str) -> None:
    """Generate CLEAN, project-owned governance state (v5.7.4 boundary): a fresh
    quality config with the project's own mode, a MASTER-PLAN from the template,
    an empty change archive, and a fresh 0/0 dashboard. No framework history,
    snapshots, owner or mode leak in — those are excluded by kit_manifest."""
    (staging / ".syntheprise-quality.yml").write_text(
        "# Syntheprise Framework project quality gate configuration.\n"
        "project:\n"
        f"  mode: {mode}   # team = review/sign-off from distinct roles; solo = one person per-role\n"
        "coverage:\n"
        "  line_threshold: 70\n"
        "# gate:\n"
        "#   integrations: strict   # opt-in (v5.10): fail `syntheprise gate` on integration drift\n",
        encoding="utf-8")
    # v5.8 kernel descriptor for the new project
    (staging / ".syntheprise").mkdir(exist_ok=True)
    (staging / ".syntheprise" / "project.yaml").write_text(
        "# Syntheprise Framework machine-readable project descriptor (v5.8 kernel).\n"
        "schema_version: 1\n"
        "kind: project\n"
        f"mode: {mode}\n"
        "# providers_dir: src/providers   # v5.10: adapter seam dir scanned by `syntheprise integrations`\n",
        encoding="utf-8")
    plans = staging / "docs" / "_plans"
    tmpl = plans / "MASTER-PLAN-template.md"
    if tmpl.exists() and not (plans / "MASTER-PLAN.md").exists():
        shutil.copy2(tmpl, plans / "MASTER-PLAN.md")
    arch = staging / "docs" / "_changes" / "_archive"
    arch.mkdir(parents=True, exist_ok=True)
    if not any(arch.iterdir()):
        (arch / ".gitkeep").write_text("", encoding="utf-8")
    # Ensure every AGENTS.md taxonomy folder exists (framework-instance content was
    # excluded, so some would otherwise be absent and fail the constitution check).
    for sub in ("_changes", "_dashboard", "_guides", "_plans", "_requirements",
                "_research", "_review", "_states", "_ui-ux_design", "adr"):
        dd = staging / "docs" / sub
        dd.mkdir(parents=True, exist_ok=True)
        if not any(dd.iterdir()):
            (dd / ".gitkeep").write_text("", encoding="utf-8")
    dash = staging / "scripts" / "syntheprise_dashboard.py"
    if dash.exists():
        subprocess.run([PY, str(dash)], cwd=staging, capture_output=True)


def _sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _write_managed_manifest(staging: Path, version: str, source_root: Path = REPO) -> None:
    """Record the SYNTHEPRISE-managed surface and each file's original SHA-256 (v5.9 provenance),
    so `syntheprise managed` can tell pristine kit files from user-modified ones and `syntheprise upgrade`
    can overwrite only the untouched ones.

    "Managed" = files copied **verbatim** from the source kit (staged bytes identical to
    the kit file). Stack-filled docs, generated project-state (`.syntheprise/project.yaml`,
    dashboard, MASTER-PLAN), markers and other team-owned files deliberately fall out —
    they are not kit-managed and must never be clobbered by an upgrade."""
    files = {}
    for rel in _base_kit_files(2, "all", root=source_root):
        sp, kp = staging / rel, source_root / rel
        if not sp.is_file() or not kp.is_file():
            continue
        sh = _sha256(sp)
        if sh != _sha256(kp):
            continue  # customized/generated at scaffold time — team-owned, not kit-managed
        files[rel] = {"sha256": sh}
    manifest = {"schema_version": 1, "source": "syntheprise-kit", "kit_version": version, "files": files}
    (staging / ".syntheprise").mkdir(exist_ok=True)
    (staging / ".syntheprise" / "managed-files.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _distributable_shas(root: Path, tier: int, adapter: str) -> dict:
    """SHA-256 of every distributable, non-secret kit file in `root` at the given
    tier/adapter — the incoming-kit surface `syntheprise upgrade` compares against."""
    out = {}
    for rel in _base_kit_files(tier, adapter, root=root):
        p = root / rel
        if p.is_file():
            out[rel] = _sha256(p)
    return out


def _top_dir(rel: str) -> str:
    return rel.split("/", 1)[0]


def _project_tier_adapter(project: Path) -> tuple:
    """Recover the tier/adapter the project was scaffolded with, from its markers, so an
    upgrade stays within the project's adopted surface (no tier-2 leak into a tier-0 app)."""
    tier = 1
    tm = project / ".syntheprise-tier"
    if tm.exists():
        try:
            tier = int(tm.read_text(encoding="utf-8").strip())
        except ValueError:
            pass
    am = project / ".syntheprise-adapter"
    adapter = am.read_text(encoding="utf-8").strip() if am.exists() else "all"
    return tier, adapter


def _upgrade_plan(project: Path, from_kit: Path):
    """Classify each managed file for a safe upgrade by comparing three hashes:
    `recorded` (kit baseline in managed-files.json), `current` (on disk now), and
    `new` (the incoming kit). Never mutates anything. Returns (plan, recorded, new_shas)."""
    manifest = json.loads((project / ".syntheprise" / "managed-files.json").read_text(encoding="utf-8"))
    recorded = {rel: meta.get("sha256") for rel, meta in manifest.get("files", {}).items()}
    tier, adapter = _project_tier_adapter(project)
    new_shas = _distributable_shas(from_kit, tier, adapter)
    managed_dirs = {_top_dir(rel) for rel in recorded}
    plan = {"update": [], "conflict": [], "add": [], "remove": [],
            "missing": [], "kept": [], "unchanged": []}
    for rel, rec in recorded.items():
        cur = _sha256(project / rel) if (project / rel).is_file() else None
        new = new_shas.get(rel)
        if cur is None:
            plan["missing"].append(rel)              # team deleted it — leave alone
        elif new is None:
            plan["remove" if cur == rec else "kept"].append(rel)  # kit dropped it
        elif cur == rec:
            plan["update" if new != rec else "unchanged"].append(rel)
        else:
            plan["conflict" if new != rec else "kept"].append(rel)  # team edited it
    for rel in new_shas:
        # A genuinely new kit file, in an adopted area, that the project does not
        # already have. Files present-but-unmanaged (stack-filled/team-owned docs)
        # are deliberately left untouched.
        if (rel not in recorded and _top_dir(rel) in managed_dirs
                and not (project / rel).exists()):
            plan["add"].append(rel)
    for k in ("update", "conflict", "add", "remove", "missing", "kept", "unchanged"):
        plan[k].sort()
    ver_file = from_kit / "VERSION"
    plan["from_version"] = ver_file.read_text(encoding="utf-8").strip() if ver_file.exists() else "?"
    plan["current_version"] = manifest.get("kit_version", "?")
    return plan, recorded, new_shas


def _apply_upgrade(project: Path, from_kit: Path, plan: dict, recorded: dict, new_shas: dict) -> None:
    """Apply an upgrade plan: overwrite pristine updates, add new files, remove dropped
    pristine files, and drop `<file>.syntheprise-new` beside each conflict (never clobbering a
    team edit). Then advance the provenance baseline to the new kit."""
    root_res = project.resolve()

    def _safe_dest(rel: str) -> Path:
        dst = project / rel
        rp = dst.resolve()
        if rp != root_res and not str(rp).startswith(str(root_res) + os.sep):
            raise RuntimeError(f"refusing to write outside project: {rel}")
        return dst

    for rel in plan["update"] + plan["add"]:
        dst = _safe_dest(rel)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(from_kit / rel, dst)
    for rel in plan["conflict"]:
        dst = _safe_dest(rel + ".syntheprise-new")
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(from_kit / rel, dst)
    for rel in plan["remove"]:
        dst = _safe_dest(rel)
        if dst.is_file():
            dst.unlink()
    adopted = (set(recorded) | set(plan["add"])) - set(plan["remove"])
    files = {rel: {"sha256": new_shas[rel]} for rel in sorted(adopted) if rel in new_shas}
    manifest = {"schema_version": 1, "source": "syntheprise-kit",
                "kit_version": plan["from_version"], "files": files}
    (project / ".syntheprise" / "managed-files.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


