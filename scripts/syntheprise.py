def _upgrade_assessment(project: Path) -> tuple[dict, int]:
    report = {
        "schema_version": 1,
        "kind": "v6-upgrade-assessment",
        "status": "unsupported",
        "detected": {
            "kit_version": _detected_kit_version(project),
            "legacy_stack": None,
            "manifest_version": None,
        },
        "target": {
            "manifest_version": 2,
            "components": [],
            "recommended_blueprint": None,
        },
        "blockers": [],
        "steps": [],
        "mutates_project": False,
    }
    if not project.is_dir():
        report["blockers"] = ["Assessment path is not a directory."]
        report["steps"] = ["Pass --path for an existing Syntheprise project."]
        return report, 2

    lock_path = project / ".syntheprise" / "stack-lock.json"
    if lock_path.is_file():
        try:
            lock = json.loads(lock_path.read_text(encoding="utf-8"))
            components = lock.get("components")
            if lock.get("schema_version") != 1 or not isinstance(
                components, list
            ) or any(not isinstance(item, str) for item in components):
                raise ValueError("invalid stack lock")
        except (OSError, json.JSONDecodeError, ValueError):
            report["blockers"] = [
                ".syntheprise/stack-lock.json is invalid; repair it before upgrade."
            ]
            report["steps"] = [
                "Run syntheprise stack plan and compare the intended composition."
            ]
            return report, 2
        report["status"] = "ready"
        report["detected"]["manifest_version"] = 2
        report["target"]["components"] = sorted(components)
        report["target"]["recommended_blueprint"] = lock.get("blueprint")
        report["steps"] = [
            "Run syntheprise managed to review locally modified kit files.",
            "Run syntheprise upgrade --from <v6-kit> as a dry-run.",
            "Review the plan and apply only through the explicit --apply command.",
            "Run syntheprise gate and the resolved stack test command.",
        ]
        return report, 0

    marker = project / ".syntheprise-stack"
    if not marker.is_file():
        report["blockers"] = [
            "No .syntheprise-stack or .syntheprise/stack-lock.json marker was found."
        ]
        report["steps"] = [
            "Identify the existing runtime, web and mobile technologies.",
            "Run syntheprise new --plan with explicit v2 selectors.",
            "Compare the plan before copying any project code.",
        ]
        return report, 2

    legacy_stack = marker.read_text(
        encoding="utf-8", errors="ignore"
    ).strip()
    report["detected"]["legacy_stack"] = legacy_stack or None
    mapping_path = SCRIPTS / "legacy-upgrade-map.json"
    try:
        mappings = json.loads(
            mapping_path.read_text(encoding="utf-8")
        ).get("stacks", {})
    except (OSError, json.JSONDecodeError):
        mappings = {}
    mapping = mappings.get(legacy_stack)
    if not isinstance(mapping, dict):
        report["blockers"] = [
            f"Legacy stack '{legacy_stack or '(empty)'} has no reviewed v6 mapping."
        ]
        report["steps"] = [
            "Choose explicit --backend/--web/--mobile selectors and review the plan."
        ]
        return report, 2

    blockers = list(mapping.get("blockers", []))
    report["status"] = "manual" if blockers else "ready"
    report["target"]["components"] = list(mapping.get("components", []))
    report["target"]["recommended_blueprint"] = mapping.get(
        "recommended_blueprint"
    )
    report["blockers"] = blockers
    report["steps"] = [
        "Commit or back up the legacy project before any migration.",
        "Scaffold the recommended v2 composition into a new empty directory.",
        "Compare environment, API and generated-client contracts.",
        "Move business code explicitly; do not overwrite the legacy project.",
        "Run the v2 stack build, test, contract-drift and health checks.",
    ]
    return report, 0


