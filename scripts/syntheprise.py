def _next_change_seq(prefix: str) -> int:
    changes = REPO / "docs" / "_changes"
    n = 0
    # Scan both active changes AND the archive, so a new id never collides with
    # an already-archived change of the same prefix/year.
    for base in (changes, changes / "_archive"):
        if not base.exists():
            continue
        for d in base.iterdir():
            # Archived folders are date-prefixed by `change archive`, for
            # example `2026-07-25-CR-2026-014-name`.
            m = re.search(
                rf"(?:^|-){re.escape(prefix)}-\d{{4}}-(\d{{3}})-",
                d.name,
            )
            if m:
                n = max(n, int(m.group(1)))
    return n + 1


def cmd_change_new(args) -> int:
    ctype = args.type.upper()
    short = re.sub(r"[^a-z0-9]+", "-", args.short.lower()).strip("-")
    year = _dt.date.today().year
    template_map = {
        "CR": "CHANGE-template", "TECH": "CHANGE-template",
        "BUG": "BUGFIX-template", "FASTLANE": "FASTLANE-template",
    }
    prefix_map = {"CR": "CR", "TECH": "TECH", "BUG": "BUGFIX", "FASTLANE": "FAST"}
    if ctype not in template_map:
        print(f"unknown change type: {ctype}", file=sys.stderr)
        return 2
    template = REPO / "docs" / "_changes" / template_map[ctype]
    if not template.exists():
        print(f"template not found: {template}", file=sys.stderr)
        return 2
    seq = _next_change_seq(prefix_map[ctype])
    change_id = f"{prefix_map[ctype]}-{year}-{seq:03d}-{short}"
    dest = REPO / "docs" / "_changes" / change_id
    if dest.exists():
        print(f"change already exists: {change_id}", file=sys.stderr)
        return 1
    shutil.copytree(template, dest)
    # Replace placeholder change-id tokens inside the copied files.
    for f in dest.rglob("*.md"):
        txt = f.read_text(encoding="utf-8")
        txt = txt.replace("CHANGE-ID-HERE", change_id).replace("BUGFIX-ID-HERE", change_id)
        f.write_text(txt, encoding="utf-8")
    print(f"created change: docs/_changes/{change_id}/")
    for f in sorted(dest.iterdir()):
        print(f"  - {f.name}")
    return 0


