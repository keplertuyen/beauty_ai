#!/usr/bin/env bash
# Generate AI-IDE rule mirrors from AGENTS.md (the single source of truth).
# Run after editing AGENTS.md so IDEs (Windsurf, legacy Cursor, Cline, Gemini CLI) pick up the rules.
# Note: Cursor and Codex read AGENTS.md natively; CLAUDE.md intentionally stays a pointer stub.
set -e
cd "$(dirname "$0")/.."
HDR='<!-- GENERATED from AGENTS.md — do not edit this file. Regenerate: bash scripts/sync-agent-rules.sh -->'
for f in .cursorrules .windsurfrules .clinerules GEMINI.md; do
  { printf '%s\n\n' "$HDR"; cat AGENTS.md; } > "$f"
  echo "wrote $f"
done
echo "Done. (Modern Cursor: prefer native AGENTS.md or .cursor/rules/*.mdc; .cursorrules is legacy-compat.)"
